import { readFileSync, writeFileSync } from "node:fs";

import { colors, radius, shadow, size, space, typography } from "../src/index.ts";

function properties(prefix, entries, unit = "") {
  return Object.entries(entries)
    .map(([key, value]) => {
      const name = key.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
      return `  --vetx-${prefix}-${name}: ${value}${unit};`;
    })
    .join("\n");
}

const css = `/* Generated by the design-tokens theme script. */
:root {
  color-scheme: light;
${properties("color", colors.light)}
${properties("space", space, "px")}
${properties("radius", radius, "px")}
${properties("type", typography, "px")}
${properties("size", size, "px")}
${properties("shadow", shadow)}
}

@media (prefers-color-scheme: dark) {
  :root {
    color-scheme: dark;
${properties("color", colors.dark)
  .split("\n")
  .map((line) => `  ${line}`)
  .join("\n")}
  }
}
`;

const target = new URL("../src/theme.css", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== css) {
    console.error(
      "Shared theme CSS is out of date. Run pnpm --filter @vetx/design-tokens sync-css.",
    );
    process.exitCode = 1;
  }
} else {
  writeFileSync(target, css);
}
